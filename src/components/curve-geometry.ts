export function curveY(x: number) {
  const clamped = Math.max(0, Math.min(800, x));
  const index = Math.min(CURVE_POINTS.length - 2, Math.floor(clamped / 4));
  const [a, b] = [CURVE_POINTS[index], CURVE_POINTS[index + 1]];
  return a[1] + ((b[1] - a[1]) * (clamped - a[0])) / (b[0] - a[0]);
}
